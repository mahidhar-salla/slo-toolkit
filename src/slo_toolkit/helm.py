"""Values for charts/slo-rules: the rule groups plus the dashboard JSON."""

from __future__ import annotations

from .dashboard import render_dashboard
from .rules import rule_groups, to_yaml
from .spec import Spec


def render_values(spec: Spec) -> str:
    values = {
        "service": spec.service,
        "ruleLabels": {"release": "kube-prometheus-stack"},
        "groups": rule_groups(spec)["groups"],
        "dashboard": {"enabled": True, "label": "grafana_dashboard", "json": render_dashboard(spec)},
    }
    header = "# Generated by slo-toolkit. Install with: helm install <name> charts/slo-rules -f <this file>\n"
    return header + to_yaml(values)
